def _ageing_block(
    ws: Worksheet, d: ReportData, key: str, label: str, start_row: int, labeller=lambda s: s
) -> tuple[int, int, int]:
    """One age-band matrix (rows = key values). Returns (header_row, first, last)."""
    labels = [
        label,
        *AGE_BUCKETS,
        "Total open",
        "Past due",
        "Critical or major",
        "High-risk (model)",
        "Median age (h)",
    ]
    ws.cell(row=start_row - 1, column=1, value=f"Open tickets by {label.lower()} and age band")
    ws.cell(row=start_row - 1, column=1).font = Font(bold=True)
    _header(ws, start_row, labels)
    ot = d.open_tickets
    keys = sorted(ot[key].unique()) if not ot.empty else []
    first = start_row + 1
    for i, k in enumerate(keys):
        r = first + i
        sub = ot[ot[key] == k]
        counts = sub["age_bucket"].value_counts()
        ws.cell(row=r, column=1, value=labeller(k))
        for j, bucket in enumerate(AGE_BUCKETS):
            ws.cell(row=r, column=2 + j, value=int(counts.get(bucket, 0))).number_format = FMT_INT
        ws.cell(row=r, column=7, value=f"=SUM(B{r}:F{r})").number_format = FMT_INT
        ws.cell(row=r, column=8, value=int(sub["past_due"].sum())).number_format = FMT_INT
        ws.cell(
            row=r, column=9, value=int(sub["severity"].isin(["critical", "major"]).sum())
        ).number_format = FMT_INT
        ws.cell(
            row=r, column=10, value=int((sub["risk_band"] == "high").sum())
        ).number_format = FMT_INT
        ws.cell(
            row=r, column=11, value=round(float(sub["age_hours"].astype(float).median()), 1)
        ).number_format = FMT_HOURS
        _style_row(ws, r, 1, len(labels))
    last = first + max(len(keys), 1) - 1
    total = last + 1
    _sum_row(ws, total, first, last, list(range(2, 11)))
    ws.cell(
        row=total,
        column=11,
        value=round(float(ot["age_hours"].astype(float).median()), 1) if not ot.empty else None,
    )
    ws.cell(row=total, column=11).number_format = FMT_HOURS
    _style_row(ws, total, 1, len(labels), fill=TOTAL_FILL, font=TOTAL_FONT)
    for col in range(2, 11):
        ws.cell(row=total, column=col).number_format = FMT_INT
    ws.conditional_formatting.add(
        f"H{first}:H{last}",
        DataBarRule(start_type="num", start_value=0, end_type="max", color="C00000"),
    )
    return start_row, first, last


