# Workbook helpers
# ------------------------------------------------------------------------------------------
def _v(value: Any) -> Any:
    """A pandas/DB value as something openpyxl writes cleanly (None for missing)."""
    if value is None:
        return None
    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, pd.Timestamp):
        return value.to_pydatetime()
    if isinstance(value, float | int | str | bool | datetime | date):
        if isinstance(value, float) and pd.isna(value):
            return None
        return value
    if hasattr(value, "item"):  # numpy scalar
        return value.item()
    if pd.isna(value):
        return None
    return value


def _pct(value: Any) -> float | None:
    """A 0-100 percentage from the views as an Excel fraction (0-1)."""
    v = _v(value)
    return None if v is None else round(v / 100.0, 6)


def _title(ws: Worksheet, title: str, subtitle: str, banner: str = SYNTHETIC_BANNER) -> None:
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws["A2"] = subtitle
    ws["A2"].font = SUBTITLE_FONT
    ws["A3"] = banner
    ws["A3"].font = BANNER_FONT


def _header(ws: Worksheet, row: int, labels: list[str], col: int = 1) -> None:
    for i, label in enumerate(labels):
        c = ws.cell(row=row, column=col + i, value=label)
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BOX
    ws.row_dimensions[row].height = 30


def _widths(ws: Worksheet, widths: dict[str, float]) -> None:
    for col, w in widths.items():
        ws.column_dimensions[col].width = w


def _style_row(ws: Worksheet, row: int, first_col: int, last_col: int, **kw: Any) -> None:
    for col in range(first_col, last_col + 1):
        c = ws.cell(row=row, column=col)
        for k, val in kw.items():
            setattr(c, k, val)
        c.border = BOX


def _delta_formatting(ws: Worksheet, cell_range: str, higher_is_better: bool) -> None:
    up, down = (GOOD_FILL, GOOD_FONT), (BAD_FILL, BAD_FONT)
    if not higher_is_better:
        up, down = down, up
    ws.conditional_formatting.add(
        cell_range, CellIsRule(operator="greaterThan", formula=["0"], fill=up[0], font=up[1])
    )
    ws.conditional_formatting.add(
        cell_range, CellIsRule(operator="lessThan", formula=["0"], fill=down[0], font=down[1])
    )


def _sum_row(
    ws: Worksheet,
    row: int,
    first_data_row: int,
    last_data_row: int,
    cols: list[int],
    label_col: int = 1,
    label: str = "Total",
) -> None:
    ws.cell(row=row, column=label_col, value=label)
    for col in cols:
        letter = get_column_letter(col)
        ws.cell(
            row=row, column=col, value=f"=SUM({letter}{first_data_row}:{letter}{last_data_row})"
        )


