@dataclass
class ReportData:
    week_ending: date
    week_start: date
    as_of: datetime  # backlog snapshot = Monday 00:00 UTC after the week
    trend: pd.DataFrame  # v_weekly_kpi, the TREND_WEEKS weeks ending with the report week
    by_customer: pd.DataFrame
    by_service: pd.DataFrame
    open_tickets: pd.DataFrame  # f_open_tickets(as_of)
    at_risk: pd.DataFrame  # top-N of open_tickets by probability
    snapshot_ts: datetime
    model_version: str | None
    generated_at: datetime
    source: str


def _query(engine: Engine, sql: str, **params: Any) -> pd.DataFrame:
    with engine.connect() as conn:
        return pd.read_sql(text(sql), conn, params=params or None)


def available_weeks(engine: Engine) -> list[date]:
    weeks = _query(engine, "SELECT week_ending FROM v_weekly_kpi ORDER BY week_ending")
    return [pd.Timestamp(w).date() for w in weeks["week_ending"]]


def default_week_ending(engine: Engine) -> date:
    """The last full Monday-Sunday week before the load snapshot."""
    weeks = available_weeks(engine)
    if not weeks:
        raise SystemExit("v_weekly_kpi is empty: is the database loaded? (make load)")
    return weeks[-1]


def parse_week_ending(value: str) -> date:
    try:
        d = date.fromisoformat(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"{value!r} is not a YYYY-MM-DD date") from exc
    if d.weekday() != 6:
        raise argparse.ArgumentTypeError(f"{value} is not a Sunday; weeks run Monday to Sunday")
    return d


def _to_naive_utc(s: pd.Series) -> pd.Series:
    s = pd.to_datetime(s, utc=True)
    return s.dt.tz_convert("UTC").dt.tz_localize(None)


def fetch(
    engine: Engine, week_ending: date | None = None, top_n: int = DEFAULT_TOP_N
) -> ReportData:
    weeks = available_weeks(engine)
    if not weeks:
        raise SystemExit("v_weekly_kpi is empty: is the database loaded? (make load)")
    week_ending = week_ending or weeks[-1]
    if week_ending not in weeks:
        raise SystemExit(
            f"no full week ends on {week_ending}; available weeks end {weeks[0]} to {weeks[-1]}"
        )
    if weeks.index(week_ending) < 1:
        raise SystemExit(f"{week_ending} is the first week in the data; nothing to compare with")

    trend = _query(
        engine,
        """
        SELECT * FROM (
            SELECT * FROM v_weekly_kpi WHERE week_ending <= :w ORDER BY week_ending DESC LIMIT :n
        ) t ORDER BY week_ending
        """,
        w=week_ending,
        n=TREND_WEEKS,
    )
    prior_week = week_ending - timedelta(days=7)
    by_customer = _query(
        engine,
        """
        SELECT cur.*,
               prev.sla_compliance_pct AS prior_week_compliance_pct
        FROM v_weekly_kpi_by_customer cur
        LEFT JOIN v_weekly_kpi_by_customer prev
               ON prev.customer_id = cur.customer_id AND prev.week_ending = :p
        WHERE cur.week_ending = :w
        ORDER BY cur.breached_tickets DESC, cur.tickets_opened DESC, cur.customer_name
        """,
        w=week_ending,
        p=prior_week,
    )
    by_service = _query(
        engine,
        """
        SELECT cur.*,
               prev.sla_compliance_pct AS prior_week_compliance_pct
        FROM v_weekly_kpi_by_service cur
        LEFT JOIN v_weekly_kpi_by_service prev
               ON prev.service_type = cur.service_type AND prev.week_ending = :p
        WHERE cur.week_ending = :w
        ORDER BY cur.breached_tickets DESC, cur.service_type
        """,
        w=week_ending,
        p=prior_week,
    )
    as_of = datetime.combine(week_ending + timedelta(days=1), datetime.min.time(), tzinfo=UTC)
    open_tickets = _query(
        engine,
        "SELECT * FROM f_open_tickets(:as_of) ORDER BY probability DESC NULLS LAST, creation_ts",
        as_of=as_of,
    )
    for col in ("creation_ts", "expected_resolution_ts"):
        open_tickets[col] = _to_naive_utc(open_tickets[col])
    at_risk = open_tickets[open_tickets["probability"].notna()].head(top_n).reset_index(drop=True)

    meta = _query(engine, "SELECT max(snapshot_ts) AS snapshot_ts FROM load_run")
    snapshot_ts = pd.Timestamp(meta["snapshot_ts"].iloc[0]).to_pydatetime()
    mv = _query(engine, "SELECT min(model_version) AS v FROM ticket_risk_score")["v"].iloc[0]
    url = engine.url.render_as_string(hide_password=True)
    return ReportData(
        week_ending=week_ending,
        week_start=week_ending - timedelta(days=6),
        as_of=as_of.replace(tzinfo=None),
        trend=trend,
        by_customer=by_customer,
        by_service=by_service,
        open_tickets=open_tickets,
        at_risk=at_risk,
        snapshot_ts=snapshot_ts,
        model_version=None if mv is None or pd.isna(mv) else str(mv),
        generated_at=datetime.now(UTC),
        source=f"PostgreSQL {url}",
    )


