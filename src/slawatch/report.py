def default_out_path(week_ending: date, reports_dir: Path = DEFAULT_REPORTS_DIR) -> Path:
    return reports_dir / f"synthetic_weekly_kpi_{week_ending.isoformat()}.xlsx"


def write_report(
    engine: Engine,
    week_ending: date | None = None,
    out: Path | None = None,
    top_n: int = DEFAULT_TOP_N,
    reports_dir: Path = DEFAULT_REPORTS_DIR,
) -> tuple[Path, ReportData]:
    data = fetch(engine, week_ending, top_n=top_n)
    out = out or default_out_path(data.week_ending, reports_dir)
    out.parent.mkdir(parents=True, exist_ok=True)
    build_workbook(data).save(out)
    log.info("wrote %s (week ending %s, %d at-risk rows)", out, data.week_ending, len(data.at_risk))
    return out, data


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Weekly KPI report (.xlsx) from the slawatch views.")
    p.add_argument(
        "--week-ending",
        type=parse_week_ending,
        default=None,
        help="Sunday, YYYY-MM-DD (default: the last full week in the data)",
    )
    p.add_argument(
        "--out",
        type=Path,
        default=None,
        help="output .xlsx (default: <out-dir>/synthetic_weekly_kpi_<week>.xlsx)",
    )
    p.add_argument(
        "--out-dir",
        type=Path,
        default=DEFAULT_REPORTS_DIR,
        help="directory for the default file name",
    )
    p.add_argument("--top-n", type=int, default=DEFAULT_TOP_N, help="rows on the at-risk sheet")
    p.add_argument("--database-url", default=None, help="defaults to $DATABASE_URL")
    return p


def main(argv: list[str] | None = None) -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
    args = build_parser().parse_args(argv)
    engine = db.get_engine(args.database_url)
    out, data = write_report(
        engine, args.week_ending, args.out, top_n=args.top_n, reports_dir=args.out_dir
    )
    t = data.trend.iloc[-1]
    log.info(
        "week ending %s: opened %d, resolved %d, compliance %.2f%%, breaches %d, "
        "p50 %.1f h, p90 %.1f h, backlog %d (%d past due, %d high-risk)",
        data.week_ending,
        t.tickets_opened,
        t.tickets_resolved,
        t.sla_compliance_pct,
        t.breached_tickets,
        t.p50_resolution_hours,
        t.p90_resolution_hours,
        t.open_backlog,
        t.backlog_past_due,
        t.high_risk_open,
    )
    print(out)


if __name__ == "__main__":
    main()
